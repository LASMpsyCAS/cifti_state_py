"""Permutation: the null distribution built from the data instead of assumed.

Random field theory answers "how surprising is this?" from a model of the
field -- Gaussian or t, smooth, stationary enough.  Permutation answers the
same question by rearranging the data under the null hypothesis and looking at
what comes out.  It needs no distributional assumption and no smoothness
estimate, and its family-wise error control is exact by construction, at the
cost of doing the analysis a few thousand times.

The two are worth having together: when they agree you can believe the answer,
and when they disagree the RFT assumptions are where to look.

**How the null is built.** Under the null the effect of interest is absent, so
the rows of the model's *residuals* are exchangeable:

* a one-sample or paired test is symmetric about zero, so the null is generated
  by flipping the sign of each subject's map;
* a two-sample test says the group labels carry no information, so the null is
  generated by shuffling them.

With nuisance covariates in the model the naive version is wrong -- shuffling
the raw data destroys the covariate relationship too -- so this uses
Freedman-Lane: the nuisance-only model is fitted first, and it is *its*
residuals that get permuted, leaving the covariate structure intact.

**How it stays fast.** Refitting the whole model a few thousand times would be
slow, but almost none of that work is new: the design never changes, only the
row order.  Writing the permuted fit in terms of ``pinv(X)`` with its columns
permuted turns each permutation into one small matrix product, and the residual
sum of squares comes from a p x p form rather than an n x n one.  A few
thousand permutations over a whole cortical surface then cost minutes rather
than hours -- and the loop reports progress and honours a cancel token, because
it is still the slowest thing in the package.

Reference: Winkler AM, Ridgway GR, Webster MA, Smith SM, Nichols TE (2014).
*Permutation inference for the general linear model.* NeuroImage 92:381-397.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

import numpy as np
from scipy.sparse import csr_matrix
from scipy.sparse.csgraph import connected_components

from ..logging_setup import get_logger
from ..types import CancelToken, ProgressFn, check_cancelled, report_progress

log = get_logger(__name__)

__all__ = ["PermutationResult", "permutation_test", "cluster_labels"]


@dataclass
class PermutationResult:
    """Null distributions of the maximum statistic and the maximum cluster."""

    max_statistic: np.ndarray        #: (n_permutations,) max |t| or max t
    max_extent: np.ndarray           #: (n_permutations,) largest cluster, in vertices
    max_mass: np.ndarray             #: (n_permutations,) largest cluster, summed statistic
    n_permutations: int
    exhaustive: bool                 #: every possible rearrangement was used
    scheme: str                      #: sign_flip | shuffle
    direction: str
    cluster_forming: float
    extent: int
    seed: Optional[int] = None
    notes: list[str] = field(default_factory=list)
    #: (n_permutations,) max TFCE score, when TFCE was asked for.
    max_tfce: Optional[np.ndarray] = None
    tfce_settings: Optional[dict] = None

    # -- p values ----------------------------------------------------------- #

    def statistic_pvalue(self, observed) -> np.ndarray:
        """FWE-corrected P for a statistic height, by the max-statistic rule."""
        return _tail_pvalue(np.asarray(observed, dtype=float), self.max_statistic)

    def extent_pvalue(self, observed) -> np.ndarray:
        """FWE-corrected P for a cluster's extent in vertices."""
        return _tail_pvalue(np.asarray(observed, dtype=float), self.max_extent)

    def mass_pvalue(self, observed) -> np.ndarray:
        """FWE-corrected P for a cluster's mass (its summed statistic)."""
        return _tail_pvalue(np.asarray(observed, dtype=float), self.max_mass)

    def tfce_pvalue(self, observed) -> np.ndarray:
        """FWE-corrected P per vertex, from the max-TFCE null.

        TFCE scores every vertex, so this is a whole map of corrected P values
        rather than one number per cluster -- which is the point of it: no
        cluster-forming threshold had to be chosen to get here.
        """
        if self.max_tfce is None:
            raise ValueError(
                "this permutation test did not compute TFCE; pass a TFCE "
                "engine to permutation_test, or tfce=True to the group test"
            )
        return _tail_pvalue(np.asarray(observed, dtype=float), self.max_tfce)

    def tfce_threshold(self, alpha: float = 0.05) -> float:
        """The TFCE score a vertex needs to reach corrected *alpha*."""
        if self.max_tfce is None:
            raise ValueError("this permutation test did not compute TFCE")
        return float(np.quantile(self.max_tfce, 1.0 - alpha))

    # -- thresholds --------------------------------------------------------- #

    def statistic_threshold(self, alpha: float = 0.05) -> float:
        return float(np.quantile(self.max_statistic, 1.0 - alpha))

    def extent_threshold(self, alpha: float = 0.05) -> float:
        return float(np.quantile(self.max_extent, 1.0 - alpha))

    def resolution(self) -> float:
        """The smallest P value this many rearrangements can produce."""
        return 1.0 / self.n_permutations

    def describe(self) -> str:
        return (
            f"{self.n_permutations} {self.scheme} permutations"
            f"{' (exhaustive)' if self.exhaustive else ''}: "
            f"max |t| threshold {self.statistic_threshold(0.05):.3f}, "
            f"cluster extent threshold {self.extent_threshold(0.05):.0f} vertices "
            f"at u={self.cluster_forming:g}"
            + (
                f", TFCE threshold {self.tfce_threshold(0.05):.3g}"
                if self.max_tfce is not None else ""
            )
            + f"; smallest reportable P {self.resolution():.2g}"
        )

    def to_dict(self) -> dict:
        return {
            "n_permutations": int(self.n_permutations),
            "exhaustive": bool(self.exhaustive),
            "scheme": self.scheme,
            "direction": self.direction,
            "cluster_forming": float(self.cluster_forming),
            "extent": int(self.extent),
            "seed": self.seed,
            "statistic_threshold_05": self.statistic_threshold(0.05),
            "extent_threshold_05": self.extent_threshold(0.05),
            "resolution": self.resolution(),
            "tfce": None if self.max_tfce is None else {
                **(self.tfce_settings or {}),
                "threshold_05": self.tfce_threshold(0.05),
            },
        }


#: Relative slack when counting the null values that beat the observed one.
#: The observed statistic and the identity rearrangement's are the same number
#: arrived at by two routes -- the fit, and the permuted-pseudoinverse form the
#: loop uses -- so they agree only to the last few bits.  Without a little
#: slack that rounding would occasionally push the observed value past its own
#: entry in the null and produce P = 0, which no permutation test can mean.
_TIE_TOLERANCE = 1e-10


def _tail_pvalue(observed: np.ndarray, null: np.ndarray) -> np.ndarray:
    """``#{null >= observed} / n`` -- PALM's convention, and never zero.

    The unpermuted arrangement is itself one of the arrangements under the
    null, and it is the first entry of every null distribution here.  So it is
    already counted once, which is what keeps the smallest possible P value at
    ``1/n`` rather than at the impossible zero -- and it must not be counted
    *twice*, which is what the familiar ``(b+1)/(m+1)`` form would do given a
    null that already contains it.  PALM counts it once; so does this.
    """
    null = np.sort(np.asarray(null, dtype=float))
    n = null.size
    observed = np.asarray(observed, dtype=float)
    slack = np.abs(observed) * _TIE_TOLERANCE
    at_least = n - np.searchsorted(null, observed - slack, side="left")
    return at_least / n


# --------------------------------------------------------------------------- #
# clustering, stripped to what the loop needs
# --------------------------------------------------------------------------- #


def cluster_labels(
    values: np.ndarray,
    adjacency: csr_matrix,
    threshold: float,
    *,
    extent: int = 1,
    mask: Optional[np.ndarray] = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Sizes and masses of the supra-threshold clusters of *values*.

    A deliberately bare version of :func:`cifti_state.core.cluster.find_clusters`:
    no labelling, no bookkeeping, no hemispheres -- it runs a few thousand
    times and only its two summary numbers are ever used.
    """
    above = values > threshold
    if mask is not None:
        above &= mask
    index = np.flatnonzero(above)
    if index.size == 0:
        return np.zeros(0), np.zeros(0)

    sub = adjacency[index][:, index]
    _, membership = connected_components(sub, directed=False)
    sizes = np.bincount(membership)
    masses = np.bincount(membership, weights=values[index])
    keep = sizes >= extent
    return sizes[keep].astype(float), masses[keep]


