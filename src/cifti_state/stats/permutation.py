# the test
# --------------------------------------------------------------------------- #


def permutation_test(
    data: np.ndarray,
    design_matrix: np.ndarray,
    contrast: np.ndarray,
    adjacency: csr_matrix,
    *,
    scheme: str = "auto",
    n_permutations: int = 5000,
    cluster_forming: float = 3.0,
    extent: int = 1,
    direction: str = "two_sided",
    mask: Optional[np.ndarray] = None,
    tfce_engine=None,
    seed: Optional[int] = 0,
    batch: int = 64,
    progress: Optional[ProgressFn] = None,
    cancel: Optional[CancelToken] = None,
) -> PermutationResult:
    """Build the null distributions of the maximum statistic and cluster.

    *adjacency* must cover the same vertices as *data*'s columns -- for a
    two-hemisphere analysis that is the block-diagonal graph of both
    hemispheres, which keeps clusters from leaping the midline.

    ``scheme="auto"`` picks sign flipping when the model is an intercept alone
    (a one-sample or paired test) and shuffling otherwise.

    Passing a :class:`~cifti_state.stats.tfce.TFCEEngine` as *tfce_engine* adds
    the max-TFCE null distribution, which is the only thing that turns a TFCE
    score into a P value.  It is by far the most expensive part of the loop, so
    it is opt-in.
    """
    y = np.asarray(data, dtype=np.float64)
    x = np.asarray(design_matrix, dtype=np.float64)
    c = np.asarray(contrast, dtype=np.float64).ravel()
    n_obs, n_vertices = y.shape

    if x.shape[0] != n_obs:
        raise ValueError("the design and the data disagree about the sample size")
    if adjacency.shape[0] != n_vertices:
        raise ValueError(
            f"the adjacency covers {adjacency.shape[0]} vertices but the data "
            f"has {n_vertices}"
        )

    nuisance = np.flatnonzero(np.abs(c) < 1e-12)
    if scheme == "auto":
        scheme = "sign_flip" if _is_intercept_only(x, c) else "shuffle"
    if scheme not in ("sign_flip", "shuffle"):
        raise ValueError(f"unknown scheme {scheme!r}")

    # Freedman-Lane: permute the residuals of the nuisance-only model, so the
    # covariate structure survives the rearrangement.
    if nuisance.size:
        z = x[:, nuisance]
        reduced_residuals = y - z @ (np.linalg.pinv(z) @ y)
        notes = [f"Freedman-Lane on {nuisance.size} nuisance predictor(s)"]
    else:
        reduced_residuals = y
        notes = []

    rank = int(np.linalg.matrix_rank(x))
    dof = float(n_obs - rank)
    pinv = np.linalg.pinv(x)                      # (p, n)
    xtx = x.T @ x                                 # (p, p)
    variance_factor = float(c @ np.linalg.pinv(xtx) @ c)
    scale = 1.0 / np.sqrt(variance_factor / dof)

    total_ss = np.einsum("ij,ij->j", reduced_residuals, reduced_residuals)

    rearrangements, exhaustive = _rearrangements(
        n_obs, scheme, n_permutations, seed,
        groups=None if scheme == "sign_flip" else _group_from_contrast(x, c),
    )
    n_permutations = len(rearrangements)
    notes.append(f"{n_permutations} rearrangements")

    vertex_mask = None if mask is None else np.asarray(mask, dtype=bool)
    absolute = direction == "two_sided"

    max_statistic = np.empty(n_permutations)
    max_extent = np.zeros(n_permutations)
    max_mass = np.zeros(n_permutations)
    max_tfce = np.zeros(n_permutations) if tfce_engine is not None else None

    log.info(
        "permutation: %s, %d rearrangements%s, u=%g, extent>=%d, %s%s",
        scheme, n_permutations, " (exhaustive)" if exhaustive else "",
        cluster_forming, extent, direction,
        f", TFCE ({tfce_engine.settings.describe()})" if tfce_engine else "",
    )

    done = 0
    for start in range(0, n_permutations, batch):
        check_cancelled(cancel)
        block = rearrangements[start:start + batch]

        # One matrix product for the whole block: pinv(X) with its columns
        # rearranged is the permuted fit, so nothing has to be refitted.
        weights = np.concatenate([_apply(pinv, r, scheme) for r in block], axis=0)
        betas = weights @ reduced_residuals          # (len(block) * p, V)
        betas = betas.reshape(len(block), x.shape[1], n_vertices)

        effect = np.einsum("p,bpv->bv", c, betas)
        explained = np.einsum("bpv,pq,bqv->bv", betas, xtx, betas)
        residual_ss = np.maximum(total_ss[None, :] - explained, 0.0)

        with np.errstate(divide="ignore", invalid="ignore"):
            t = scale * effect / np.sqrt(residual_ss)
        t[~np.isfinite(t)] = 0.0
        if vertex_mask is not None:
            t[:, ~vertex_mask] = 0.0

        for row in range(len(block)):
            values = np.abs(t[row]) if absolute else (
                -t[row] if direction == "negative" else t[row]
            )
            max_statistic[done] = values.max() if values.size else 0.0
            sizes, masses = cluster_labels(
                values, adjacency, cluster_forming,
                extent=extent, mask=vertex_mask,
            )
            max_extent[done] = sizes.max() if sizes.size else 0.0
            max_mass[done] = masses.max() if masses.size else 0.0
            if max_tfce is not None:
                # TFCE is scored on exactly the same map the other statistics
                # see -- |t| for a two-tailed test, as PALM does it.
                max_tfce[done] = tfce_engine(values).max()
            done += 1

        report_progress(
            progress, done / n_permutations,
            f"permutation {done}/{n_permutations}",
        )

    result = PermutationResult(
        max_statistic=max_statistic,
        max_extent=max_extent,
        max_mass=max_mass,
        n_permutations=n_permutations,
        exhaustive=exhaustive,
        scheme=scheme,
        direction=direction,
        cluster_forming=float(cluster_forming),
        extent=int(extent),
        seed=seed,
        notes=notes,
        max_tfce=max_tfce,
        tfce_settings=(
            tfce_engine.settings.to_dict() if tfce_engine is not None else None
        ),
    )
    log.info("permutation: %s", result.describe())
    return result


