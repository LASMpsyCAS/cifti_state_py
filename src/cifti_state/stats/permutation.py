def _is_intercept_only(x: np.ndarray, c: np.ndarray) -> bool:
    """Is the tested predictor a column of ones, with nothing else tested?"""
    tested = np.flatnonzero(np.abs(c) > 1e-12)
    if tested.size != 1:
        return False
    column = x[:, tested[0]]
    return bool(np.allclose(column, column[0]) and column[0] != 0)


def _group_from_contrast(x: np.ndarray, c: np.ndarray) -> Optional[np.ndarray]:
    """The two-level predictor being tested, if that is what it is."""
    tested = np.flatnonzero(np.abs(c) > 1e-12)
    if tested.size != 1:
        return None
    column = x[:, tested[0]]
    levels = np.unique(column)
    if levels.size == 2:
        return (column == levels[1]).astype(int)
    return None


def _apply(pinv: np.ndarray, rearrangement: np.ndarray, scheme: str) -> np.ndarray:
    """``pinv(X)`` with its columns permuted, or their signs flipped."""
    if scheme == "sign_flip":
        return pinv * rearrangement[None, :]
    return pinv[:, rearrangement]


def _rearrangements(
    n: int, scheme: str, requested: int, seed: Optional[int],
    *, groups: Optional[np.ndarray] = None,
) -> tuple[list[np.ndarray], bool]:
    """The rearrangements to use, with the identity always first.

    When the number of distinct rearrangements is smaller than the number
    requested, all of them are used and the test becomes exact rather than
    approximate -- and that is reported, because it changes how the smallest
    possible P value should be read.
    """
    rng = np.random.default_rng(seed)

    if scheme == "sign_flip":
        total = 2 ** n
        if total <= requested:
            signs = [
                np.array([1.0 if not (i >> bit) & 1 else -1.0 for bit in range(n)])
                for i in range(total)
            ]
            return signs, True
        out = [np.ones(n)]
        seen = {out[0].tobytes()}
        while len(out) < requested:
            candidate = rng.choice([-1.0, 1.0], size=n)
            key = candidate.tobytes()
            if key in seen:
                continue
            seen.add(key)
            out.append(candidate)
        return out, False

    identity = np.arange(n)

    # With a two-group design only the split matters, and there are C(n, n1) of
    # them. When that is fewer than asked for, enumerate the lot: the test is
    # then exact rather than approximate.
    if groups is not None:
        from itertools import combinations
        from math import comb

        labels = np.asarray(groups)
        positions = np.flatnonzero(labels == 1)
        total = comb(n, positions.size)
        if total <= max(requested, 1):
            out = []
            for chosen in combinations(range(n), positions.size):
                order = np.empty(n, dtype=int)
                mask = np.zeros(n, dtype=bool)
                mask[list(chosen)] = True
                order[mask] = positions
                order[~mask] = np.flatnonzero(labels == 0)
                out.append(order)
            # Put the identity first so the observed arrangement leads.
            for index, order in enumerate(out):
                if np.array_equal(labels[order], labels):
                    out[0], out[index] = out[index], out[0]
                    break
            return out, True

    out = [identity]
    seen = {identity.tobytes()}
    attempts = 0
    limit = requested * 20
    while len(out) < requested and attempts < limit:
        attempts += 1
        candidate = rng.permutation(n)
        # Two permutations that produce the same group split give the same
        # statistic, so keep only distinct splits when there is a grouping.
        key = (
            candidate.tobytes() if groups is None
            else np.asarray(groups)[candidate].tobytes()
        )
        if key in seen:
            continue
        seen.add(key)
        out.append(candidate)
    return out, False
