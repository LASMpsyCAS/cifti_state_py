def test_the_unpermuted_rearrangement_supplies_the_observed_tfce():
    """The identity leads the null, so the observed score is its first entry.

    This is the hinge the whole correction turns on: the observed map has to be
    scored by exactly the same function as every rearrangement, or the P value
    compares two different statistics.
    """
    from cifti_state.stats.glm import fit_glm
    from cifti_state.stats.permutation import permutation_test

    rng = np.random.default_rng(21)
    n = 120
    graph, area = chain(n), np.ones(n)
    data = rng.normal(size=(12, n))
    data[:, 40:60] += 1.2
    design = np.ones((12, 1))
    contrast = np.array([1.0])

    engine = TFCEEngine(graph, area, settings=PALM_DEFAULT)
    result = permutation_test(
        data, design, contrast, graph, n_permutations=64,
        cluster_forming=2.0, tfce_engine=engine, seed=0,
    )
    observed = engine(np.abs(fit_glm(data, design, contrast).t))

    assert result.max_tfce is not None
    assert result.max_tfce[0] == pytest.approx(observed.max(), rel=1e-12)
    assert result.tfce_settings == PALM_DEFAULT.to_dict()


def test_the_tfce_null_gives_p_values_between_the_resolution_and_one():
    from cifti_state.stats.glm import fit_glm
    from cifti_state.stats.permutation import permutation_test

    rng = np.random.default_rng(22)
    n = 100
    graph = chain(n)
    data = rng.normal(size=(10, n))
    data[:, 30:50] += 2.0
    design, contrast = np.ones((10, 1)), np.array([1.0])
    engine = TFCEEngine(graph, np.ones(n))
    result = permutation_test(
        data, design, contrast, graph,
        n_permutations=128, cluster_forming=2.0, tfce_engine=engine, seed=1,
    )

    observed = engine(np.abs(fit_glm(data, design, contrast).t))
    p = result.tfce_pvalue(observed)
    assert p.min() >= result.resolution() - 1e-15
    assert p.max() <= 1.0
    # A score of zero is beaten by every rearrangement.
    assert float(result.tfce_pvalue(0.0)) == pytest.approx(1.0)
    assert result.tfce_threshold(0.05) > 0
    assert "TFCE" in result.describe()


def test_asking_for_tfce_p_values_without_a_tfce_null_is_refused():
    from cifti_state.stats.permutation import permutation_test

    rng = np.random.default_rng(23)
    graph = chain(60)
    result = permutation_test(
        rng.normal(size=(8, 60)), np.ones((8, 1)), np.array([1.0]), graph,
        n_permutations=32, cluster_forming=2.0, seed=0,
    )
    assert result.max_tfce is None
    with pytest.raises(ValueError, match="did not compute TFCE"):
        result.tfce_pvalue(1.0)


def test_the_permutation_loop_is_deterministic_under_a_seed():
    from cifti_state.stats.permutation import permutation_test

    rng = np.random.default_rng(24)
    n = 80
    graph = chain(n)
    data = rng.normal(size=(9, n))
    engine = TFCEEngine(graph, np.ones(n))
    kwargs = dict(n_permutations=48, cluster_forming=2.0, tfce_engine=engine, seed=5)
    a = permutation_test(data, np.ones((9, 1)), np.array([1.0]), graph, **kwargs)
    b = permutation_test(data, np.ones((9, 1)), np.array([1.0]), graph, **kwargs)
    assert np.array_equal(a.max_tfce, b.max_tfce)


def test_the_settings_describe_themselves():
    assert "H=2" in PALM_DEFAULT.describe()
    assert "auto" in PALM_DEFAULT.describe()
    assert "E=1" in PALM_2D.describe()
    assert TFCESettings(dh=0.25).describe().endswith("0.25")
    assert PALM_DEFAULT.to_dict() == {"H": 2.0, "E": 0.5, "dh": 0.0, "steps": 100}
