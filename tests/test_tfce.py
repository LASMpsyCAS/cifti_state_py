def test_the_engine_and_the_one_shot_agree_and_the_engine_is_reusable():
    """Reusing an engine must not let one map's state leak into the next."""
    rng = np.random.default_rng(7)
    graph, area = chain(120), rng.uniform(0.5, 2.0, size=120)
    engine = TFCEEngine(graph, area, settings=PALM_DEFAULT)

    maps = [np.abs(rng.normal(size=120)) for _ in range(4)]
    first = [engine(m) for m in maps]
    again = [engine(m) for m in reversed(maps)][::-1]     # a different order

    for m, once, twice in zip(maps, first, again):
        assert np.array_equal(once, twice)
        assert np.allclose(once, tfce(m, graph, area), rtol=0, atol=0)


def test_a_mesh_and_an_area_vector_that_disagree_are_refused():
    with pytest.raises(ValueError, match="areas"):
        TFCEEngine(chain(10), np.ones(11))


def test_a_map_of_the_wrong_length_is_refused():
    engine = TFCEEngine(chain(10), np.ones(10))
    with pytest.raises(ValueError, match="vertices"):
        engine(np.ones(11))


