"""TFCE: agreement with PALM, and the properties that follow from the formula.

The first and most important test compares this implementation against the
real ``palm_tfce.m``.  PALM's output was generated by running that MATLAB
function in Octave over four meshes -- different sizes, masked and unmasked,
and three settings of ``H``/``E`` -- and the results are stored verbatim in
``tests/data/palm_tfce_reference.npz``.  Nothing here re-derives what PALM
should have produced; the numbers in that file *are* PALM's, printed at full
double precision, and agreement is asserted at 1e-12 relative, which is a
loose bound on the 1e-15 the two actually achieve.

The rest of the file checks the things the integral

    TFCE(v) = ∫ e(h)^E · h^H dh

implies exactly, so that a future change that still matched PALM's four
reference maps by luck would not also survive these: how the score scales with
the map, with the areas, and with each exponent; that the mask and the mesh's
connectivity are respected; and that a map with nothing above zero scores zero.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest
from scipy.sparse import csr_matrix

from cifti_state.stats.tfce import (
    PALM_2D,
    PALM_DEFAULT,
    TFCEEngine,
    TFCESettings,
    tfce,
)

REFERENCE = Path(__file__).parent / "data" / "palm_tfce_reference.npz"


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #


def adjacency_from_faces(faces: np.ndarray, n: int) -> csr_matrix:
    """The edge graph of a triangulation, symmetric and unweighted."""
    f = np.asarray(faces)
    a = np.concatenate([f[:, 0], f[:, 0], f[:, 1], f[:, 1], f[:, 2], f[:, 2]])
    b = np.concatenate([f[:, 1], f[:, 2], f[:, 0], f[:, 2], f[:, 0], f[:, 1]])
    m = csr_matrix((np.ones(a.size, np.int8), (a, b)), shape=(n, n))
    m.data[:] = 1
    return m


def chain(n: int) -> csr_matrix:
    """A path graph: vertex i touches i-1 and i+1, and nothing else."""
    rows = list(range(n - 1)) + list(range(1, n))
    cols = list(range(1, n)) + list(range(n - 1))
    return csr_matrix((np.ones(len(rows)), (rows, cols)), shape=(n, n))


@pytest.fixture(scope="module")
def palm_cases():
    """PALM's own output for four meshes, as generated by palm_tfce.m."""
    if not REFERENCE.exists():          # pragma: no cover - fixture is committed
        pytest.skip("the PALM reference file is not present")
    return np.load(REFERENCE, allow_pickle=False)


