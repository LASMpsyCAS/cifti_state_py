def test_a_map_with_nothing_positive_scores_zero():
    """No height is above any step, so PALM's loop body never runs."""
    graph = chain(20)
    area = np.ones(20)
    assert not np.any(tfce(-np.arange(1.0, 21.0), graph, area))
    assert not np.any(tfce(np.zeros(20), graph, area))


def test_scaling_the_map_scales_the_score_by_c_to_the_H_plus_one():
    """With the automatic ladder the steps scale with the map, so ``c^(H+1)``.

    ``h^H`` contributes ``c^H`` and the ``dh`` the integral is multiplied by
    contributes another factor of ``c``.  The extent never changes, because
    scaling a map cannot change which vertices are above a proportionally
    scaled threshold -- which is exactly why the automatic ladder makes the
    score comparable across permutations of wildly different magnitude.
    """
    rng = np.random.default_rng(3)
    values = np.abs(rng.normal(size=200))
    graph, area = chain(200), np.ones(200)
    for height in (1.0, 2.0, 3.0):
        settings = TFCESettings(height=height, extent=0.5)
        base = tfce(values, graph, area, settings=settings)
        scaled = tfce(7.0 * values, graph, area, settings=settings)
        assert np.allclose(scaled, 7.0 ** (height + 1.0) * base, rtol=1e-10)


def test_scaling_the_areas_scales_the_score_by_c_to_the_E():
    """Extent enters only as ``e(h)^E``, and area is what extent means here."""
    rng = np.random.default_rng(4)
    values = np.abs(rng.normal(size=150))
    graph = chain(150)
    for extent in (0.25, 0.5, 1.0):
        settings = TFCESettings(extent=extent)
        base = tfce(values, graph, np.ones(150), settings=settings)
        bigger = tfce(values, graph, np.full(150, 3.0), settings=settings)
        assert np.allclose(bigger, 3.0 ** extent * base, rtol=1e-10)


def test_extent_is_area_and_not_a_vertex_count():
    """Two clusters of equal area score alike however finely each is cut.

    On a real surface the tessellation is uneven, so a vertex count would hand
    an advantage to whichever region happens to be sampled more densely.  Here
    one blob is four vertices of area 1 and the other is eight of area 0.5.
    """
    graph = chain(40)
    area = np.ones(40)
    area[20:28] = 0.5
    values = np.zeros(40)
    values[4:8] = 2.0                    # 4 vertices x 1.0  = 4 mm²
    values[20:28] = 2.0                  # 8 vertices x 0.5  = 4 mm²

    scores = tfce(values, graph, area)
    assert scores[4:8].max() == pytest.approx(scores[20:28].max(), rel=1e-12)


def test_the_mask_removes_a_vertex_from_the_cluster_it_would_have_joined():
    """A masked vertex scores zero *and* stops the cluster passing through it."""
    graph = chain(30)
    area = np.ones(30)
    values = np.zeros(30)
    values[10:21] = 3.0                  # eleven vertices, 15 in the middle

    mask = np.ones(30, dtype=bool)
    mask[15] = False                     # cut the run in half
    scores = tfce(values, graph, area, mask=mask)

    assert scores[15] == 0.0
    whole = tfce(values, graph, area)
    # Half the extent, so a smaller score for every surviving member.
    assert np.all(scores[10:15] < whole[10:15])
    # Five vertices either side of the cut, and the two halves score alike.
    assert scores[10] == pytest.approx(scores[20], rel=1e-12)
    assert scores[10] == pytest.approx(scores[16], rel=1e-12)


def test_clusters_do_not_leap_a_gap_in_the_graph():
    """Connectivity comes from the mesh, not from the vertex numbering."""
    n = 40
    left, right = chain(20), chain(20)
    from scipy.sparse import block_diag

    graph = csr_matrix(block_diag((left, right), format="csr"))
    values = np.zeros(n)
    values[18:22] = 2.0                  # 18,19 in one block; 20,21 in the other
    scores = tfce(values, graph, np.ones(n))

    joined = tfce(values, chain(n), np.ones(n))     # the same run, now connected
    assert np.all(scores[18:22] < joined[18:22])


def test_a_larger_extent_exponent_favours_the_broad_bump_over_the_spike():
    """The point of E: it is the dial between focal and diffuse effects."""
    n = 300
    graph, area = chain(n), np.ones(n)
    values = np.zeros(n)
    values[50] = 6.0                                  # a tall, narrow spike
    values[150:190] = 3.0                             # a broad, lower bump

    focal = tfce(values, graph, area, settings=TFCESettings(extent=0.1))
    diffuse = tfce(values, graph, area, settings=PALM_2D)   # E = 1
    assert focal[50] > focal[150:190].max()
    assert diffuse[150:190].max() > diffuse[50]


def test_a_taller_height_exponent_favours_the_spike_over_the_bump():
    """And H is the same dial turned the other way."""
    n = 300
    graph, area = chain(n), np.ones(n)
    values = np.zeros(n)
    values[50] = 6.0
    values[150:190] = 3.0

    flat = tfce(values, graph, area, settings=TFCESettings(height=0.5, extent=1.0))
    steep = tfce(values, graph, area, settings=TFCESettings(height=6.0, extent=1.0))
    assert flat[150:190].max() > flat[50]
    assert steep[50] > steep[150:190].max()


def test_a_fixed_step_reproduces_the_automatic_one_when_it_is_the_same_step():
    """The two ladder branches are one ladder, built two ways.

    PALM's own surface branch cannot run with a fixed ``dh`` -- it never
    assigns the variable it multiplies by -- so this is the only handle there
    is on that path: set the fixed step to what the automatic one would have
    chosen, and the two must agree.
    """
    rng = np.random.default_rng(31)
    values = np.abs(rng.normal(size=180))
    graph, area = chain(180), np.ones(180)

    automatic = tfce(values, graph, area, settings=TFCESettings(steps=100))
    fixed = tfce(values, graph, area,
                 settings=TFCESettings(dh=values.max() / 100))
    assert np.allclose(automatic, fixed, rtol=1e-9)

    # And a coarser fixed step really is coarser, rather than being ignored.
    coarse = tfce(values, graph, area, settings=TFCESettings(dh=values.max() / 5))
    assert not np.allclose(automatic, coarse, rtol=1e-3)


def test_more_steps_converge_on_the_integral():
    """The ladder is a quadrature, so refining it should stop changing much."""
    rng = np.random.default_rng(11)
    values = np.abs(rng.normal(size=250))
    graph, area = chain(250), np.ones(250)

    coarse = tfce(values, graph, area, settings=TFCESettings(steps=100))
    fine = tfce(values, graph, area, settings=TFCESettings(steps=400))
    finer = tfce(values, graph, area, settings=TFCESettings(steps=1600))

    assert np.abs(fine - finer).max() < np.abs(coarse - fine).max()
    assert np.abs(fine - finer).max() / finer.max() < 0.01


