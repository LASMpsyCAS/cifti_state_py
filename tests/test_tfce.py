@pytest.mark.parametrize("tag", ["c1", "c2", "c3", "c6"])
def test_matches_palm_to_machine_precision(palm_cases, tag):
    """The reference implementation, vertex for vertex."""
    height, extent, dh, n_vertices = palm_cases[f"{tag}/params"]
    n_vertices = int(n_vertices)
    mask = palm_cases[f"{tag}/mask"]
    values = np.zeros(n_vertices)
    values[mask] = palm_cases[f"{tag}/values"]

    mine = tfce(
        values,
        adjacency_from_faces(palm_cases[f"{tag}/faces"], n_vertices),
        palm_cases[f"{tag}/area"],
        mask=mask,
        settings=TFCESettings(height=height, extent=extent, dh=dh),
    )[mask]

    reference = palm_cases[f"{tag}/palm"]
    relative = np.abs(mine - reference) / np.maximum(np.abs(reference), 1e-30)
    assert relative.max() < 1e-12


def test_the_reference_cases_actually_exercise_different_settings(palm_cases):
    """A guard on the fixture: four identical cases would prove very little."""
    settings = {tuple(palm_cases[f"{tag}/params"][:2]) for tag in
                ("c1", "c2", "c3", "c6")}
    assert len(settings) == 3                       # (2, .5), (2, 1), (3, .25)
    assert not palm_cases["c2/mask"].all()          # one case is masked


